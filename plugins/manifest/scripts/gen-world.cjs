// Generates ui/map/world.ts — the world silhouette of the «Сверка» map: country shapes
// (Natural Earth 1:110m via world-atlas) and marker points (1:50m, largest polygon),
// projected once with Natural Earth I. Run with the tools in a scratch directory:
//   npm i --prefix /tmp/worldgen world-atlas@2 topojson-client@3 d3-geo@3 i18n-iso-countries@7
//   node scripts/gen-world.cjs /tmp/worldgen > ui/map/world.ts
const path = require("path");
const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/gen-world.cjs <dir with node_modules>");
const req = (m) => require(path.join(dir, "node_modules", m));
const topo = req("topojson-client");
const d3 = req("d3-geo");
const iso = req("i18n-iso-countries");

const W = 960;
const H = 440;
const t110 = req("world-atlas/countries-110m.json");
const t50 = req("world-atlas/countries-50m.json");
const f110 = topo.feature(t110, t110.objects.countries).features;
const f50 = topo.feature(t50, t50.objects.countries).features;
const code = (f) => {
  const a2 = iso.numericToAlpha2(String(f.id).padStart(3, "0"));
  if (a2) return a2;
  const n = f.properties.name;
  return { Kosovo: "XK", "N. Cyprus": "CY", Somaliland: "SO" }[n] || null;
};
const land = f110.filter((f) => code(f) !== "AQ");
// Crop the far south: no suppliers below −58°.
const projection = d3.geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H + 60]], { type: "FeatureCollection", features: land });
const geoPath = d3.geoPath(projection);
const round = (s) => s.replace(/(\d+\.\d)\d+/g, "$1");

const shapes = {};
for (const f of land) {
  const c = code(f);
  if (!c) continue;
  shapes[c] = (shapes[c] || "") + round(geoPath(f));
}
// Marker point: the centroid of the largest polygon (France in Europe, not Guiana).
const points = {};
for (const f of f50) {
  const c = code(f);
  if (!c || c === "AQ") continue;
  const g = f.geometry;
  const polys = g.type === "MultiPolygon" ? g.coordinates : [g.coordinates];
  let best = null;
  let area = -1;
  for (const p of polys) {
    const a = d3.geoArea({ type: "Polygon", coordinates: p });
    if (a > area) [best, area] = [p, a];
  }
  const xy = projection(d3.geoCentroid({ type: "Polygon", coordinates: best }));
  if (xy && !points[c]) points[c] = [Math.round(xy[0]), Math.round(xy[1])];
}
// Overseas regions inside France in Natural Earth: their own points (lon, lat).
const extra = { GP: [-61.55, 16.25], MQ: [-61.0, 14.65], RE: [55.5, -21.1], GF: [-53.2, 3.9], YT: [45.15, -12.8], BL: [-62.85, 17.9], MF: [-63.05, 18.07], PM: [-56.3, 46.9], NC: [165.6, -21.3], PF: [-149.4, -17.6] };
for (const [c, ll] of Object.entries(extra)) {
  if (points[c]) continue;
  const xy = projection(ll);
  points[c] = [Math.round(xy[0]), Math.round(xy[1])];
}
const out = [
  "// Generated by scripts/gen-world.cjs from Natural Earth (world-atlas, public domain). Do not edit.",
  `export const WORLD_W = ${W};`,
  `export const WORLD_H = ${H};`,
  `/** Country shapes, ISO alpha-2 → SVG path (1:110m). */`,
  `export const SHAPES: Record<string, string> = ${JSON.stringify(shapes)};`,
  `/** Marker points, ISO alpha-2 → [x, y] (1:50m, the largest polygon). */`,
  `export const POINTS: Record<string, [number, number]> = ${JSON.stringify(points)};`,
  "",
].join("\n");
process.stdout.write(out);
